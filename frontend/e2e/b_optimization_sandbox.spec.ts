import { expect, test } from '@playwright/test';

test('isolated sandbox trains a GP, ranks candidates, and compares Branin baselines', async ({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/Playwright isolated synthetic topic/}).click();
  await page.getByRole('button',{name:'기타',exact:true}).click();
  await page.getByRole('menuitem',{name:'Optimization'}).click();
  const trainResponse=page.waitForResponse(response=>response.url().includes('/optimization/models/train')&&response.request().method()==='POST');
  const recommendation=page.waitForResponse(response=>response.url().includes('/optimization/models/')&&response.url().endsWith('/recommend'));
  await page.getByRole('button',{name:'GP 학습 후 다음 조건 추천'}).click();
  const trained=await trainResponse;
  expect(trained.ok()).toBeTruthy();
  const model=await trained.json();
  expect(model.mode).toBe('sandbox');
  expect(model.config.sample_count).toBe(24);
  const result=await recommendation;
  expect(result.ok()).toBeTruthy();
  const payload=await result.json();
  expect(payload.candidates).toHaveLength(5);
  expect(payload.approval_status).toBe('PENDING_RESEARCHER_REVIEW');
  await expect(page.getByText('연구자 검토 필요').first()).toBeVisible();
  await expect(page.getByText(/Branin \(synthetic sandbox\)/)).toBeVisible({timeout:90_000});
  await expect(page.getByText(/GP \+ EI 중앙 최선값/)).toBeVisible();

  await page.getByRole('combobox').first().selectOption('noisy');
  const stage2Response=page.waitForResponse(response=>response.url().includes('/optimization/sandbox/benchmark/stage2')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'벤치마크 실행'}).click();
  const stage2=await stage2Response;
  expect(stage2.ok()).toBeTruthy();
  const stage2Payload=await stage2.json();
  expect(stage2Payload.noisy.policies.gp_noisy_ei.runs).toBe(5);
  await expect(page.getByText('Phase 4 · Stage 2 합성 벤치마크')).toBeVisible();
  await expect(page.getByRole('heading',{name:/노이즈 최적화/})).toBeVisible();
});

test('multiobjective sandbox trains two GPs, shows Pareto hypervolume and persists a reviewed batch', async ({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/Playwright isolated synthetic topic/}).click();
  await page.getByRole('button',{name:'기타',exact:true}).click();
  await page.getByRole('menuitem',{name:'Optimization'}).click();
  await expect(page.getByText('다목적 최적화 · Pareto 추천')).toBeVisible();
  const trained=page.waitForResponse(response=>response.url().includes('/optimization/multiobjective/models/train')&&response.request().method()==='POST');
  const recommendationResponse=page.waitForResponse(response=>response.url().includes('/optimization/multiobjective/models/')&&response.url().endsWith('/recommend'));
  await page.getByRole('button',{name:'두 목적 GP 학습 후 후보 묶음 추천'}).click();
  const trainResponse=await trained;
  expect(trainResponse.ok()).toBeTruthy();
  const trainPayload=await trainResponse.json();
  expect(trainPayload.model_type).toBe('gpbo-moo-stage3-1');
  const recommendResponse=await recommendationResponse;
  expect(recommendResponse.ok()).toBeTruthy();
  const recommendation=await recommendResponse.json();
  expect(recommendation.candidates).toHaveLength(2);
  expect(recommendation.approval_status).toBe('PENDING_RESEARCHER_REVIEW');
  await expect(page.getByText('2차원 Pareto 지도')).toBeVisible();
  await expect(page.getByText(/연구자 검토 대기/).first()).toBeVisible();
  await expect(page.getByText(new RegExp(`추천 ID: ${recommendation.recommendation_id}`))).toBeVisible();
  const comparisonResponse=page.waitForResponse(response=>response.url().includes('/optimization/multiobjective/sandbox/benchmark/compare')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'다목적 알고리즘 비교 실행 · 5개 시드'}).click();
  const comparison=await comparisonResponse;
  expect(comparison.ok()).toBeTruthy();
  const benchmark=await comparison.json();
  expect(Object.keys(benchmark.benchmarks)).toEqual(['ZDT1','Branin-Currin']);
  expect(benchmark.benchmarks.ZDT1.policies.greedy_batch_mc_hvi.runs).toHaveLength(5);
  await expect(page.getByText('샌드박스 알고리즘 비교')).toBeVisible();
  await expect(page.getByText(/Branin-Currin/).last()).toBeVisible();
});

test('learned decision head trains on isolated synthetic fixtures and compares in shadow mode', async ({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/Playwright isolated synthetic topic/}).click();
  await page.getByRole('button',{name:'기타',exact:true}).click();
  await page.getByRole('menuitem',{name:'Decision'}).click();
  const seedResponse=page.waitForResponse(response=>response.url().includes('/decisions/learned/sandbox/seed')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'합성 테스트 데이터 만들기'}).click();
  expect((await seedResponse).ok()).toBeTruthy();
  const trainResponse=page.waitForResponse(response=>response.url().includes('/decisions/learned/train')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'학습 실행'}).click();
  const trained=await trainResponse;
  expect(trained.ok()).toBeTruthy();
  const model=await trained.json();
  expect(model.mode).toBe('sandbox');
  expect(model.metrics.training_loss_decreased).toBeTruthy();
  await expect(page.getByText('모델 검증 결과')).toBeVisible();
  const compare=page.waitForResponse(response=>response.url().includes('/decisions/learned/compare')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'규칙과 학습 결과 비교'}).click();
  const comparison=await compare;
  expect(comparison.ok()).toBeTruthy();
  const result=await comparison.json();
  expect(result.mode).toBe('SHADOW_ONLY');
  expect(result.workflow_triggered).toBe(false);
  await expect(page.getByText('학습형 추천')).toBeVisible();
  await expect(page.getByText(/워크플로 실행 안 함/)).toBeVisible();
});
