import { expect, test } from '@playwright/test';

test('PHREEQC planner accepts structured analytical inputs only after explicit approval', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: /Playwright isolated synthetic topic/ }).click();
  await page.getByRole('button', { name: '분석', exact: true }).click();
  await page.getByRole('textbox', { name: '연구 목표' }).fill('PHREEQC 수용액 평형 계산');
  const inputs = page.locator('.phreeqc-workflow-inputs');
  await expect(inputs).toBeVisible();
  await expect(inputs.locator('input[type=number]').nth(0)).toHaveValue('');
  await expect(inputs.locator('input[type=number]').nth(1)).toHaveValue('');
  await expect(inputs.locator('textarea')).toHaveValue('{}');
  await page.getByRole('button', { name: '계획 만들기' }).click();
  await expect(page.locator('.analysis-error')).toBeVisible();
  await inputs.locator('input[type=number]').nth(0).fill('25');
  await inputs.locator('input[type=number]').nth(1).fill('7');
  await inputs.locator('textarea').fill('{"Ca": 0.001, "C(4)": 0.001}');
  await inputs.locator('input:not([type=number]):not([type=checkbox])').fill('Calcite');
  const unapprovedPreview = page.waitForResponse(response => response.url().includes('/workflows/plan') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '계획 만들기' }).click();
  const previewPayload = await (await unapprovedPreview).json();
  expect(previewPayload.approval_required).toBeTruthy();
  expect(previewPayload.executable).toBeFalsy();
  await inputs.locator('input[type=checkbox]').check();
  await page.getByRole('button', { name: '계획 만들기' }).click();
  await expect(page.getByText('계획한 작업 등록')).toBeVisible({ timeout: 20_000 });
  await expect(page.locator('.workflow-plan ol li').filter({ hasText: 'phreeqc.aqueous_equilibrium.v1' })).toBeVisible();
  const queuedResponse = page.waitForResponse(response => response.url().includes('/workflows/plan') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '계획한 작업 등록' }).click();
  const queued = await queuedResponse;
  const payload = await queued.json();
  expect(queued.ok(), JSON.stringify(payload)).toBeTruthy();
  expect(payload.workflow?.nodes?.some((node: {tool_id:string}) => node.tool_id === 'phreeqc.aqueous_equilibrium.v1')).toBeTruthy();
  const workflowId = payload.workflow.id as number;
  const topicId = payload.workflow.topic_id as number;
  const workerStarted = await page.request.post('/__e2e/start-worker');
  expect([200, 409]).toContain(workerStarted.status());
  await expect.poll(async () => {
    const response = await page.request.get(`/api/workflows/${workflowId}?topic_id=${topicId}`);
    return response.ok() ? (await response.json()).status : `HTTP ${response.status()}`;
  }, { timeout: 45_000 }).toBe('COMPLETED');
  const completed = await (await page.request.get(`/api/workflows/${workflowId}?topic_id=${topicId}`)).json();
  expect(completed.id).toBe(workflowId);
  expect(completed.status).toBe('COMPLETED');
  const phreeqcNode = completed.nodes.find((node: {tool_id:string}) => node.tool_id === 'phreeqc.aqueous_equilibrium.v1');
  expect(phreeqcNode).toBeTruthy();
  expect(phreeqcNode.status).toBe('COMPLETED');
  expect(phreeqcNode.result_type).toBe('simulation_run');
  expect(phreeqcNode.result_id).toBeTruthy();
  expect(phreeqcNode.output?.source_type).toBe('SIMULATION');
  expect(phreeqcNode.output?.validation?.valid).toBeTruthy();
  const simulationRows = await (await page.request.get(`/api/analysis/simulation-runs?topic_id=${topicId}`)).json();
  const simulation = simulationRows.find((row: {id:number}) => row.id === phreeqcNode.result_id);
  expect(simulation).toBeTruthy();
  expect(simulation.results?.provenance?.tool_id).toBe('phreeqc.aqueous_equilibrium.v1');
  expect(simulation.results?.provenance?.database_sha256).toMatch(/^[a-f0-9]{64}$/);
  await page.reload();
  await page.getByRole('button', { name: '분석', exact: true }).click();
  const persistedResponse = await page.request.get(`/api/workflows/${workflowId}?topic_id=${topicId}`);
  expect(persistedResponse.ok()).toBeTruthy();
  const persisted = await persistedResponse.json();
  expect(persisted.id).toBe(workflowId);
  expect(persisted.status).toBe('COMPLETED');
  expect(persisted.nodes.find((node: {tool_id:string}) => node.tool_id === 'phreeqc.aqueous_equilibrium.v1')?.result_id).toBe(phreeqcNode.result_id);
  const afterRefreshRuns = await (await page.request.get(`/api/analysis/simulation-runs?topic_id=${topicId}`)).json();
  expect(afterRefreshRuns.find((row: {id:number}) => row.id === phreeqcNode.result_id)?.results?.provenance?.tool_id).toBe('phreeqc.aqueous_equilibrium.v1');
});
