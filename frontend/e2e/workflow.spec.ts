import { expect, test } from '@playwright/test';

test('isolated topic can plan, enqueue, reload, and inspect a durable XRD run', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '연구 주제 선택' })).toBeVisible();
  await page.getByRole('button', { name: /Playwright isolated synthetic topic/ }).click();
  await page.getByRole('button', { name: '분석', exact: true }).click();
  await expect(page.getByText('저장형 과학 분석 흐름')).toBeVisible();
  await page.getByRole('textbox', { name: '연구 목표' }).fill('XRD 회절 피크 분석');
  await page.getByRole('button', { name: '계획 만들기' }).click();
  await expect(page.getByText('계획한 작업 등록')).toBeVisible({ timeout: 20_000 });
  const enqueueResponse = page.waitForResponse(response => response.url().includes('/workflows/plan') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '계획한 작업 등록' }).click();
  const queued = await enqueueResponse;
  const queuedPayload = await queued.json();
  expect(queued.ok(), JSON.stringify(queuedPayload)).toBeTruthy();
  expect(queuedPayload.workflow?.id, JSON.stringify(queuedPayload)).toBeTruthy();
  const firstWorkflowId = queuedPayload.workflow.id as number;
  const topicId = queuedPayload.workflow.topic_id as number;
  const firstCard = page.locator('.workflow-job').filter({ hasText: `Workflow #${firstWorkflowId}` });
  await expect(firstCard).toBeVisible({ timeout: 20_000 });
  await firstCard.getByRole('button', { name: '취소' }).click();
  await expect(firstCard.locator('.workflow-status.cancelled')).toBeVisible({ timeout: 20_000 });
  const secondEnqueueResponse = page.waitForResponse(response => response.url().includes('/workflows/plan') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '계획한 작업 등록' }).click();
  const secondEnqueue = await secondEnqueueResponse;
  const secondPayload = await secondEnqueue.json();
  expect(secondEnqueue.ok(), JSON.stringify(secondPayload)).toBeTruthy();
  expect(secondPayload.workflow?.id).toBeTruthy();
  const xrdWorkflowId = secondPayload.workflow.id as number;
  const xrdTopicId = secondPayload.workflow.topic_id as number;
  const started = await page.request.post('/__e2e/start-worker');
  expect([200, 409]).toContain(started.status());
  await expect.poll(async () => {
    const response = await page.request.get(`/api/workflows/${xrdWorkflowId}?topic_id=${xrdTopicId}`);
    return response.ok() ? (await response.json()).status : `HTTP ${response.status()}`;
  }, { timeout: 45_000 }).toBe('COMPLETED');
  const xrdCompleted = await (await page.request.get(`/api/workflows/${xrdWorkflowId}?topic_id=${xrdTopicId}`)).json();
  const xrdNode = xrdCompleted.nodes.find((node: {tool_id:string}) => node.tool_id === 'xrd.local_peaks.v1');
  expect(xrdNode).toMatchObject({status:'COMPLETED', result_type:'analysis_run'});
  expect(xrdNode.result_id).toBeTruthy();
  await page.reload();
  await page.getByRole('button', { name: '분석', exact: true }).click();
  const xrdAfterReload = await (await page.request.get(`/api/workflows/${xrdWorkflowId}?topic_id=${xrdTopicId}`)).json();
  expect(xrdAfterReload.id).toBe(xrdWorkflowId);
  expect(xrdAfterReload.status).toBe('COMPLETED');
  expect(xrdAfterReload.nodes.find((node: {tool_id:string}) => node.tool_id === 'xrd.local_peaks.v1')?.result_id).toBe(xrdNode.result_id);
  const isolated = await page.request.get('/api/workflows?topic_id=999999');
  expect(await isolated.json()).toEqual([]);
  const experiments = page.locator('.durable-workflow-start select').first();
  await experiments.selectOption({ label: 'E2E-XRD-FAIL · Synthetic invalid XRD retry · 2026-01-02' });
  await page.getByRole('button', { name: '계획 만들기' }).click();
  await expect(page.getByRole('button', { name: '계획한 작업 등록' })).toBeVisible();
  const failedEnqueueResponse = page.waitForResponse(response => response.url().includes('/workflows/plan') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '계획한 작업 등록' }).click();
  const failedResponse = await failedEnqueueResponse;
  expect(failedResponse.ok()).toBeTruthy();
  const failedPayload = await failedResponse.json();
  const failedId = failedPayload.workflow.id as number;
  const failedCard = page.locator('.workflow-job').filter({ hasText: `Workflow #${failedId}` });
  await expect(failedCard.locator('.workflow-node.failed')).toBeVisible({ timeout: 30_000 });
  await failedCard.getByRole('button', { name: '재시도' }).click();
  await expect(failedCard.locator('.workflow-node.failed')).toBeVisible({ timeout: 30_000 });
});
